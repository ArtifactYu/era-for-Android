		/// <summary>MS ゴシックがそのコードポイントを半角で持つか。</summary>
		public static bool IsHalfWidth(int codePoint)
		{
			if (codePoint < 0 || codePoint > 0xFFFF)
				return false;
			int lo = 0, hi = halfWidth.Length / 2 - 1;
			while (lo <= hi)
			{
				int mid = (lo + hi) / 2;
				if (codePoint < halfWidth[mid * 2])
					hi = mid - 1;
				else if (codePoint > halfWidth[mid * 2 + 1])
					lo = mid + 1;
				else
					return true;
			}
			return false;
		}
	}
