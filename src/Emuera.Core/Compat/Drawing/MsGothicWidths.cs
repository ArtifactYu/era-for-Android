//
// era のスクリプトは枠や桁を「半角スペースを自分で並べる」で組み、その桁数は
// Windows の既定フォント (emuera.config の「フォント名:ＭＳ ゴシック」) の幅で合わせてある。
// MS ゴシックは JIS X 0208 にある字を全角、Unicode 拡張として足した記号を半角で持つ。
// たとえばステータスバーに使う ▋ U+258B は 0.5em (半角) で、
// 罫線の ─ U+2500 や ■ U+25A0 は 1.0em (全角)。
//
// 端末のフォントはこの分け方をしない (Noto は ▋ を全角で持つ) ため、
// <see cref="GlyphFallback"/> が代替グリフ本来の送り幅でセルを決めると
// 1 文字ごとに半角 1 桁ぶん行が伸び、罫線で組んだ枠が右へずれる
// (ShinEraTenseiP の素質選択画面がこれで崩れていた)。
//
// 表は msgothic.ttc (MS Gothic) の cmap / hmtx から採った実測値で、フォントの複製ではなく
// 「どのコードポイントが半角か」という数値だけを持つ。作り直しは:
//   Emuera.TestHarness --dump-halfwidth "MS Gothic" > 表.txt

